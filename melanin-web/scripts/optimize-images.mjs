import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const imagesDir = path.join(root, "public", "images");
const outDir = path.join(imagesDir, "opt");
const manifestPath = path.join(root, "src", "lib", "image-manifest.ts");

const photos = [
  { file: "hero-home.jpg", quality: 82 },
  { file: "hero-services.jpg", quality: 82 },
  { file: "card-1.jpg", quality: 78 },
  { file: "card-2.jpg", quality: 78 },
  { file: "card-3.jpg", quality: 78 },
  { file: "card-4.jpg", quality: 78 },
  { file: "service-ai.jpg", quality: 78 },
  { file: "service-products.jpg", quality: 78 },
  { file: "service-commerce.jpg", quality: 78 },
  { file: "service-blockchain.jpg", quality: 78 },
];

const widths = [480, 768, 1200, 1920];

const icons = [
  "favicon.png",
  "apple-touch-icon.png",
  "icon-192.png",
  "icon-512-maskable.png",
  "og-image.png",
];

function hash(buffer) {
  return createHash("sha256").update(buffer).digest("hex").slice(0, 8);
}

function kb(bytes) {
  return `${(bytes / 1024).toFixed(1)} KB`;
}

await mkdir(outDir, { recursive: true });
const written = new Set();
const manifest = {};
let before = 0;
let after = 0;

for (const { file, quality } of photos) {
  const input = path.join(imagesDir, file);
  const sourceBytes = (await readFile(input)).length;
  before += sourceBytes;
  const meta = await sharp(input).rotate().metadata();
  const sourceWidth = meta.width ?? 0;
  const targets = widths.filter((width) => width < sourceWidth - 40);
  if (!targets.includes(Math.min(sourceWidth, 1920))) targets.push(Math.min(sourceWidth, 1920));

  const variants = [];
  for (const width of targets) {
    const buffer = await sharp(input)
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality, effort: 5, smartSubsample: true })
      .toBuffer();
    const name = `${path.parse(file).name}-${width}-${hash(buffer)}.webp`;
    await writeFile(path.join(outDir, name), buffer);
    written.add(name);
    variants.push({ width, url: `/images/opt/${name}`, bytes: buffer.length });
  }

  variants.sort((a, b) => a.width - b.width);
  const fallback =
    variants.find((variant) => variant.width >= 1200) ?? variants[variants.length - 1];
  after += fallback.bytes;
  manifest[`/images/${file}`] = {
    width: sourceWidth,
    height: meta.height ?? 0,
    src: fallback.url,
    srcSet: variants.map((variant) => `${variant.url} ${variant.width}w`).join(", "),
  };
  console.log(
    `${file.padEnd(28)} ${kb(sourceBytes).padStart(10)} -> ${variants
      .map((variant) => `${variant.width}w ${kb(variant.bytes)}`)
      .join(", ")}`,
  );
}

const logoPath = path.join(imagesDir, "logo.png");
const logoBytes = (await readFile(logoPath)).length;
before += logoBytes;
const logoMeta = await sharp(logoPath).metadata();
const logoVariants = [];
for (const width of [480, 720]) {
  const buffer = await sharp(logoPath)
    .resize({ width, withoutEnlargement: true })
    .webp({ lossless: true, effort: 6 })
    .toBuffer();
  const info = await sharp(buffer).metadata();
  const name = `logo-${info.width}-${hash(buffer)}.webp`;
  await writeFile(path.join(outDir, name), buffer);
  written.add(name);
  logoVariants.push({
    width: info.width ?? width,
    height: info.height ?? 0,
    url: `/images/opt/${name}`,
    bytes: buffer.length,
  });
}
const logoFallback = logoVariants[logoVariants.length - 1];
after += logoFallback.bytes;
manifest["/images/logo.png"] = {
  width: logoMeta.width ?? logoFallback.width,
  height: logoMeta.height ?? logoFallback.height,
  src: logoFallback.url,
  srcSet: logoVariants.map((variant) => `${variant.url} ${variant.width}w`).join(", "),
};
console.log(
  `logo.png                     ${kb(logoBytes).padStart(10)} -> ${logoVariants
    .map((variant) => `${variant.width}w ${kb(variant.bytes)}`)
    .join(", ")}`,
);

const entries = Object.entries(manifest)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, asset]) => {
    const srcSet = asset.srcSet ? `, srcSet: ${JSON.stringify(asset.srcSet)}` : "";
    return `  ${JSON.stringify(key)}: { width: ${asset.width}, height: ${asset.height}, src: ${JSON.stringify(asset.src)}${srcSet} },`;
  });

const manifestSource = `/* Generated by scripts/optimize-images.mjs. Do not edit. */

export type ImageAsset = {
  width: number;
  height: number;
  src: string;
  srcSet?: string;
};

export const imageManifest: Record<string, ImageAsset> = {
${entries.join("\n")}
};
`;
await writeFile(manifestPath, manifestSource);

for (const name of await readdir(outDir)) {
  if (!written.has(name)) await rm(path.join(outDir, name));
}

for (const file of icons) {
  const filePath = path.join(root, "public", file);
  const original = await readFile(filePath);
  const compressed = await sharp(original).png({ compressionLevel: 9, effort: 10 }).toBuffer();
  if (compressed.length < original.length * 0.9) {
    await writeFile(filePath, compressed);
    console.log(
      `${file.padEnd(28)} ${kb(original.length).padStart(10)} -> ${kb(compressed.length)}`,
    );
  } else {
    console.log(`${file.padEnd(28)} ${kb(original.length).padStart(10)} unchanged`);
  }
}

console.log(
  `\nPage images: ${kb(before)} originals, typical request now uses the sized WebP variant.`,
);
